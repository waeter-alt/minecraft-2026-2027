package fr.kodistan.interregne.commerce;

import com.ldtteam.structurize.blueprints.v1.Blueprint;
import com.ldtteam.structurize.blueprints.v1.BlueprintUtil;
import net.minecraft.core.BlockPos;
import net.minecraft.data.registries.VanillaRegistries;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.NbtAccounter;
import net.minecraft.nbt.NbtIo;
import net.minecraft.world.level.block.state.BlockState;
import org.junit.jupiter.api.Test;

import java.io.InputStream;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The five Relais commercial blueprints load, hold exactly one hut at their anchor, and each level is bigger than the last.
 * The blueprints are generated by {@code mod/tools/gen_relais_blueprints.py}.
 */
class RelaisBlueprintTest
{
    private static Blueprint load(final int level) throws Exception
    {
        try (InputStream in = RelaisBlueprintTest.class.getResourceAsStream("/blueprints/interregne/interregne/commerce/relais" + level + ".blueprint"))
        {
            assertNotNull(in, "relais" + level + ".blueprint is missing from the resources");
            final CompoundTag tag = NbtIo.readCompressed(in, NbtAccounter.unlimitedHeap());
            return BlueprintUtil.readBlueprintFromNBT(tag, VanillaRegistries.createLookup());
        }
    }

    @Test
    void everyLevelHoldsTheHutAtItsAnchor() throws Exception
    {
        for (int level = 1; level <= 5; level++)
        {
            final Blueprint blueprint = load(level);
            final BlockPos anchor = blueprint.getPrimaryBlockOffset();
            final BlockState atAnchor = blueprint.getBlockState(anchor);
            assertEquals(Commerce.RELAIS_BLOCK.get(), atAnchor.getBlock(), "level " + level + ": the anchor is not the hut");

            int huts = 0;
            for (int y = 0; y < blueprint.getSizeY(); y++)
            {
                for (int z = 0; z < blueprint.getSizeZ(); z++)
                {
                    for (int x = 0; x < blueprint.getSizeX(); x++)
                    {
                        final BlockState state = blueprint.getBlockState(new BlockPos(x, y, z));
                        huts += state.getBlock() == Commerce.RELAIS_BLOCK.get() ? 1 : 0;
                    }
                }
            }
            assertEquals(1, huts, "level " + level + ": exactly one hut");
        }
    }

    @Test
    void eachLevelIsBiggerThanTheLast() throws Exception
    {
        int previous = 0;
        for (int level = 1; level <= 5; level++)
        {
            final Blueprint blueprint = load(level);
            final int volume = blueprint.getSizeX() * blueprint.getSizeY() * blueprint.getSizeZ();
            assertTrue(volume > previous, "level " + level + " should be bigger than the one before");
            previous = volume;
        }
    }
}
