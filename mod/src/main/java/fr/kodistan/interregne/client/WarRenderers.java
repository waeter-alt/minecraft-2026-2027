package fr.kodistan.interregne.client;

import com.minecolonies.core.client.render.mobs.barbarians.AbstractRendererBarbarian;
import fr.kodistan.interregne.InterregneMod;
import fr.kodistan.interregne.war.EntArcher;
import fr.kodistan.interregne.war.EntLegionnaire;
import fr.kodistan.interregne.war.WarEntities;
import net.minecraft.client.model.HumanoidModel;
import net.minecraft.client.model.geom.ModelLayers;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.resources.ResourceLocation;
import net.neoforged.api.distmarker.Dist;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.client.event.EntityRenderersEvent;

/**
 * Each troop has its own skin (generated by mod/tools/gen_visuels.py): the légionnaire in red tunic and steel armour,
 * the archer in a green hood and leather — told apart at a glance, and never mistaken for a MineColonies barbarian.
 */
@EventBusSubscriber(modid = InterregneMod.MODID, value = Dist.CLIENT)
public final class WarRenderers
{
    private static final ResourceLocation LEGIONNAIRE_TEXTURE =
      ResourceLocation.fromNamespaceAndPath(InterregneMod.MODID, "textures/entity/war/legionnaire.png");
    private static final ResourceLocation ARCHER_TEXTURE =
      ResourceLocation.fromNamespaceAndPath(InterregneMod.MODID, "textures/entity/war/archer.png");

    @SubscribeEvent
    public static void onRenderers(final EntityRenderersEvent.RegisterRenderers event)
    {
        event.registerEntityRenderer(WarEntities.LEGIONNAIRE.get(), RendererLegionnaire::new);
        event.registerEntityRenderer(WarEntities.ARCHER.get(), RendererArcher::new);
    }

    public static final class RendererLegionnaire extends AbstractRendererBarbarian<EntLegionnaire, HumanoidModel<EntLegionnaire>>
    {
        public RendererLegionnaire(final EntityRendererProvider.Context context)
        {
            super(context, new HumanoidModel<>(context.bakeLayer(ModelLayers.PLAYER_OUTER_ARMOR)), 0.5F);
        }

        @Override
        public ResourceLocation getTextureLocation(final EntLegionnaire entity)
        {
            return LEGIONNAIRE_TEXTURE;
        }
    }

    public static final class RendererArcher extends AbstractRendererBarbarian<EntArcher, HumanoidModel<EntArcher>>
    {
        public RendererArcher(final EntityRendererProvider.Context context)
        {
            super(context, new HumanoidModel<>(context.bakeLayer(ModelLayers.PLAYER_OUTER_ARMOR)), 0.5F);
        }

        @Override
        public ResourceLocation getTextureLocation(final EntArcher entity)
        {
            return ARCHER_TEXTURE;
        }
    }

    private WarRenderers()
    {
    }
}
